import { CheckCheck, Download, Loader2, Send, ThumbsUp } from "lucide-react";
import { useState } from "react";
import { Link, useSearchParams } from "react-router-dom";

import {
  type Recommendation,
  downloadRecommendationPdf,
  useRecommendationAction,
  useRecommendations,
  useRefine,
  useRefinementSession,
} from "@/api/hooks";
import { useAuth } from "@/auth/AuthContext";
import { EmptyState, ErrorState, LoadingCards, PageHeader } from "@/components/StateViews";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { cn } from "@/lib/utils";

const STATUS_VARIANT = { pending: "warning", approved: "default", confirmed: "success" } as const;

type Payload = {
  what: string;
  why: string;
  expected_behavior: string;
  goal_probability: number;
  risks: string[];
  suggested_instruments: string[];
  target_allocation: Record<string, number>;
};

function Detail({ rec }: { rec: Recommendation }) {
  const p = rec.payload as unknown as Payload;
  return (
    <div className="space-y-4 text-sm">
      <p className="text-base font-medium">{p.what}</p>
      <div className="flex flex-wrap gap-2">
        {Object.entries(p.target_allocation ?? {}).map(([k, v]) => (
          <Badge key={k} variant="secondary">
            {k}: {v}%
          </Badge>
        ))}
        {(p.suggested_instruments ?? []).map((i) => (
          <Badge key={i} variant="outline">
            {i}
          </Badge>
        ))}
      </div>
      <div>
        <p className="text-xs font-medium uppercase text-muted-foreground">Why</p>
        <p className="leading-relaxed">{p.why}</p>
      </div>
      <div>
        <p className="text-xs font-medium uppercase text-muted-foreground">Expected behaviour (estimate)</p>
        <p className="leading-relaxed">{p.expected_behavior}</p>
      </div>
      <div>
        <p className="text-xs font-medium uppercase text-muted-foreground">Risks</p>
        <ul className="list-disc pl-5">
          {(p.risks ?? []).map((r) => (
            <li key={r}>{r}</li>
          ))}
        </ul>
      </div>
      <p className="text-xs text-muted-foreground">
        Model-estimated goal probability {Math.round((p.goal_probability ?? 0) * 100)}% · generated by {rec.llm_provider} on{" "}
        {rec.generated_at.slice(0, 16).replace("T", " ")}
      </p>
    </div>
  );
}

export default function RecommendationsPage() {
  const { investorId } = useAuth();
  const [params, setParams] = useSearchParams();
  const recommendations = useRecommendations();
  const action = useRecommendationAction();
  const refine = useRefine();
  const [message, setMessage] = useState("");
  const [pdfError, setPdfError] = useState<string | null>(null);
  const [pdfLoading, setPdfLoading] = useState(false);

  const selectedId = params.get("id") ? Number(params.get("id")) : (recommendations.data?.[0]?.id ?? null);
  const selected = recommendations.data?.find((r) => r.id === selectedId) ?? null;
  const session = useRefinementSession(selectedId);

  if (recommendations.isLoading) return <LoadingCards count={2} />;
  if (recommendations.error) return <ErrorState error={recommendations.error} onRetry={() => recommendations.refetch()} />;
  if (!recommendations.data?.length) {
    return (
      <div>
        <PageHeader title="Suggestions" />
        <EmptyState
          title="No suggestions yet"
          description="Generate one on the Advice page."
          action={
            <Button asChild>
              <Link to="/advice">Go to Advice</Link>
            </Button>
          }
        />
      </div>
    );
  }

  const sendRefinement = async () => {
    if (!selected || !message.trim()) return;
    const next = await refine.mutateAsync({ id: selected.id, message: message.trim() });
    setMessage("");
    setParams({ id: String(next.id) });
  };

  const exportPdf = async () => {
    if (!selected || investorId === null) return;
    setPdfError(null);
    setPdfLoading(true);
    try {
      await downloadRecommendationPdf(investorId, selected.id);
    } catch (err) {
      setPdfError(err instanceof Error ? err.message : "Export failed");
    } finally {
      setPdfLoading(false);
    }
  };

  return (
    <div>
      <PageHeader title="Suggestions" description="Review, refine in conversation, approve and export your saved suggestions." />
      <div className="grid gap-6 lg:grid-cols-[320px_1fr]">
        <div className="space-y-2">
          {recommendations.data.map((rec) => (
            <button
              key={rec.id}
              type="button"
              onClick={() => setParams({ id: String(rec.id) })}
              className={cn(
                "block w-full rounded-lg border bg-card p-3 text-left text-sm transition-colors hover:border-primary/50",
                rec.id === selectedId && "border-primary ring-2 ring-primary/20",
              )}
            >
              <div className="flex items-center justify-between">
                <span className="font-medium">#{rec.id}</span>
                <Badge variant={STATUS_VARIANT[rec.status as keyof typeof STATUS_VARIANT] ?? "secondary"}>{rec.status}</Badge>
              </div>
              <p className="mt-1 line-clamp-2 text-muted-foreground">{(rec.payload as { what?: string }).what}</p>
            </button>
          ))}
        </div>

        {selected && (
          <div className="space-y-4">
            <Card>
              <CardHeader className="flex-row items-start justify-between gap-4">
                <div>
                  <CardTitle>Suggestion #{selected.id}</CardTitle>
                  <CardDescription>
                    Status:{" "}
                    <Badge variant={STATUS_VARIANT[selected.status as keyof typeof STATUS_VARIANT] ?? "secondary"}>
                      {selected.status}
                    </Badge>
                  </CardDescription>
                </div>
                <div className="flex flex-wrap gap-2">
                  <Button
                    size="sm"
                    variant="outline"
                    disabled={selected.status !== "pending" || action.isPending}
                    onClick={() => action.mutate({ id: selected.id, action: "approve" })}
                  >
                    <ThumbsUp /> Approve
                  </Button>
                  <Button
                    size="sm"
                    variant="outline"
                    disabled={selected.status !== "approved" || action.isPending}
                    onClick={() => action.mutate({ id: selected.id, action: "confirm" })}
                  >
                    <CheckCheck /> Confirm
                  </Button>
                  <Button size="sm" variant="outline" disabled={!selected.goal_id || pdfLoading} onClick={exportPdf}
                    title={selected.goal_id ? "Download the Investment Target Sheet" : "PDF export needs a goal-linked suggestion"}>
                    {pdfLoading ? <Loader2 className="animate-spin" /> : <Download />} PDF
                  </Button>
                </div>
              </CardHeader>
              <CardContent>
                {(action.error || pdfError) && (
                  <Alert variant="destructive" className="mb-4">
                    <AlertDescription>{action.error?.message ?? pdfError}</AlertDescription>
                  </Alert>
                )}
                <Detail rec={selected} />
              </CardContent>
            </Card>

            <Card>
              <CardHeader>
                <CardTitle>Refine</CardTitle>
                <CardDescription>
                  Ask for changes like "remove NVIDIA" or "more bonds". Each turn creates a new suggestion; earlier
                  constraints are kept.
                </CardDescription>
              </CardHeader>
              <CardContent className="space-y-3">
                {session.data?.messages.length ? (
                  <div className="space-y-2">
                    {session.data.messages.map((m) => (
                      <div key={m.id} className="space-y-1">
                        <div className="ml-auto w-fit max-w-[80%] rounded-2xl rounded-br-sm bg-primary px-3 py-2 text-sm text-primary-foreground">
                          {m.user_message}
                        </div>
                        <button
                          type="button"
                          onClick={() => setParams({ id: String(m.resulting_recommendation_id) })}
                          className="w-fit max-w-[80%] rounded-2xl rounded-bl-sm bg-muted px-3 py-2 text-left text-sm hover:bg-muted/70"
                        >
                          Updated → suggestion #{m.resulting_recommendation_id} ({m.llm_provider})
                        </button>
                      </div>
                    ))}
                  </div>
                ) : (
                  <p className="text-sm text-muted-foreground">No refinements yet for this suggestion.</p>
                )}
                {refine.error && (
                  <Alert variant="destructive">
                    <AlertDescription>{refine.error.message}</AlertDescription>
                  </Alert>
                )}
                <form
                  className="flex gap-2"
                  onSubmit={(e) => {
                    e.preventDefault();
                    sendRefinement();
                  }}
                >
                  <Input
                    value={message}
                    onChange={(e) => setMessage(e.target.value)}
                    placeholder="e.g. more international exposure"
                    disabled={refine.isPending || !selected.goal_id}
                  />
                  <Button disabled={refine.isPending || !message.trim() || !selected.goal_id}>
                    {refine.isPending ? <Loader2 className="animate-spin" /> : <Send />}
                  </Button>
                </form>
                {!selected.goal_id && (
                  <p className="text-xs text-muted-foreground">Refinement needs a suggestion that was planned against a goal.</p>
                )}
              </CardContent>
            </Card>
          </div>
        )}
      </div>
    </div>
  );
}
